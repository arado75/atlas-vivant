  if (city.importance) {
    return city;
  }

  if (highImportanceCityIds.has(city.id)) {
    return { ...city, importance: "high" };
  }

  if (lowImportanceCityIds.has(city.id)) {
    return { ...city, importance: "low" };
  }

  return { ...city, importance: "medium" };
